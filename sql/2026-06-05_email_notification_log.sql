CREATE TABLE EMAIL_NOTIFICATION_LOG (
    EMAIL_LOG_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FORMID NUMBER NOT NULL,
    APPROVALID NUMBER,
    EVENT_TYPE VARCHAR2(50) NOT NULL,
    RECIPIENT_EMPID NUMBER,
    RECIPIENT_EMAIL VARCHAR2(320) NOT NULL,
    SUBJECT VARCHAR2(500) NOT NULL,
    BODY CLOB,
    STATUS VARCHAR2(20) DEFAULT 'READY' NOT NULL,
    SEND_ATTEMPT NUMBER DEFAULT 0 NOT NULL,
    DEDUPE_KEY VARCHAR2(500) NOT NULL,
    CREATED_BY NUMBER,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_ATTEMPT_AT TIMESTAMP,
    NEXT_ATTEMPT_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    SENT_AT TIMESTAMP,
    ERROR_MESSAGE VARCHAR2(1000),
    CONSTRAINT UQ_EMAIL_NOTIFICATION_DEDUPE UNIQUE (DEDUPE_KEY),
    CONSTRAINT CHK_EMAIL_NOTIFICATION_STATUS CHECK (
        STATUS IN ('READY', 'PENDING', 'SENDING', 'SENT', 'FAILED', 'SKIPPED')
    )
);

CREATE INDEX IX_EMAIL_NOTI_LOG_FORMID ON EMAIL_NOTIFICATION_LOG (FORMID);
CREATE INDEX IX_EMAIL_NOTI_LOG_STATUS ON EMAIL_NOTIFICATION_LOG (STATUS);
CREATE INDEX IX_EMAIL_NOTI_LOG_DUE ON EMAIL_NOTIFICATION_LOG (STATUS, NEXT_ATTEMPT_AT);

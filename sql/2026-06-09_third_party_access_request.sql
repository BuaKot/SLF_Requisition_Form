CREATE TABLE THIRD_PARTY_ACCESS_REQUEST (
    ACCESS_REQUEST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SUBMISSION_ID NUMBER NOT NULL,
    DISPLAY_ORDER NUMBER NOT NULL,
    EMPLOYEE_CODE VARCHAR2(100 CHAR),
    USERNAME VARCHAR2(150 CHAR),
    NATIONAL_ID VARCHAR2(13),
    FULL_NAME_TH VARCHAR2(255 CHAR) NOT NULL,
    FULL_NAME_EN VARCHAR2(255 CHAR),
    POSITION_NAME VARCHAR2(255 CHAR) NOT NULL,
    MOBILE_PHONE VARCHAR2(50 CHAR) NOT NULL,
    DEPARTMENT_NAME VARCHAR2(255 CHAR) NOT NULL,
    EMAIL VARCHAR2(320) NOT NULL,
    SYSTEM_NAME VARCHAR2(255 CHAR) NOT NULL,
    REQUESTED_ROLE VARCHAR2(1000 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_TP_ACCESS_SUBMISSION FOREIGN KEY (SUBMISSION_ID)
        REFERENCES THIRD_PARTY_FORM_SUBMISSION (SUBMISSION_ID) ON DELETE CASCADE,
    CONSTRAINT UQ_TP_ACCESS_DISPLAY_ORDER UNIQUE (SUBMISSION_ID, DISPLAY_ORDER)
);

CREATE INDEX IX_TP_ACCESS_SUBMISSION
    ON THIRD_PARTY_ACCESS_REQUEST (SUBMISSION_ID);

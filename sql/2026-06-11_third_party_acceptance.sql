CREATE TABLE THIRD_PARTY_ACCEPTANCE_TOKEN (
    ACCEPTANCE_TOKEN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REQUEST_ID NUMBER NOT NULL,
    TOKEN_HASH VARCHAR2(64) NOT NULL,
    RAW_TOKEN VARCHAR2(120),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    EXPIRES_AT TIMESTAMP NOT NULL,
    USED_AT TIMESTAMP,
    CONSTRAINT FK_TP_ACCEPT_TOKEN_REQUEST FOREIGN KEY (REQUEST_ID)
        REFERENCES THIRD_PARTY_REQUEST (REQUEST_ID),
    CONSTRAINT UQ_TP_ACCEPT_TOKEN_HASH UNIQUE (TOKEN_HASH),
    CONSTRAINT UQ_TP_ACCEPT_TOKEN_REQUEST UNIQUE (REQUEST_ID),
    CONSTRAINT CHK_TP_ACCEPT_TOKEN_STATUS CHECK (
        STATUS IN ('ACTIVE', 'USED', 'EXPIRED', 'REVOKED')
    )
);

CREATE INDEX IX_TP_ACCEPT_TOKEN_STATUS
    ON THIRD_PARTY_ACCEPTANCE_TOKEN (STATUS, EXPIRES_AT);

CREATE TABLE THIRD_PARTY_ACCEPTANCE_RESULT (
    ACCEPTANCE_RESULT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REQUEST_ID NUMBER NOT NULL,
    COMMENT_TEXT CLOB NOT NULL,
    SATISFACTION_LEVEL NUMBER NOT NULL,
    SUBMITTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_TP_ACCEPT_RESULT_REQUEST FOREIGN KEY (REQUEST_ID)
        REFERENCES THIRD_PARTY_REQUEST (REQUEST_ID),
    CONSTRAINT UQ_TP_ACCEPT_RESULT_REQUEST UNIQUE (REQUEST_ID),
    CONSTRAINT CHK_TP_ACCEPT_RESULT_LEVEL CHECK (SATISFACTION_LEVEL BETWEEN 1 AND 5)
);


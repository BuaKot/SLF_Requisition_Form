CREATE TABLE THIRD_PARTY_REQUEST (
    REQUEST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FORM_CODE VARCHAR2(80) DEFAULT 'THIRD_PARTY_USER_REGISTRATION' NOT NULL,
    INTERNAL_OWNER_EMPID NUMBER NOT NULL,
    EXTERNAL_COMPANY_NAME VARCHAR2(255),
    EXTERNAL_CONTACT_NAME VARCHAR2(255),
    EXTERNAL_EMAIL VARCHAR2(320),
    EXTERNAL_PHONE VARCHAR2(50),
    PURPOSE CLOB,
    TARGET_SYSTEM VARCHAR2(500),
    ACCESS_START_DATE DATE,
    ACCESS_END_DATE DATE,
    STATUS VARCHAR2(30) DEFAULT 'LINK_CREATED' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    SUBMITTED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CHK_THIRD_PARTY_REQ_STATUS CHECK (
        STATUS IN ('LINK_CREATED', 'SUBMITTED', 'PENDING_REVIEW', 'APPROVED', 'REJECTED', 'CANCELLED')
    ),
    CONSTRAINT CHK_THIRD_PARTY_REQ_OWNER_678 CHECK (INTERNAL_OWNER_EMPID = 678),
    CONSTRAINT CHK_THIRD_PARTY_REQ_DATES CHECK (
        ACCESS_START_DATE IS NULL OR ACCESS_END_DATE IS NULL OR ACCESS_END_DATE >= ACCESS_START_DATE
    )
);

CREATE INDEX IX_THIRD_PARTY_REQ_OWNER
    ON THIRD_PARTY_REQUEST (INTERNAL_OWNER_EMPID, CREATED_AT);

CREATE INDEX IX_THIRD_PARTY_REQ_STATUS
    ON THIRD_PARTY_REQUEST (STATUS, CREATED_AT);


-- Third-party request workflow.
-- Run once as SLF_USER before or during deployment.
-- SUBMITTED remains temporarily allowed so the currently deployed application
-- can continue accepting forms until the new package is deployed.

CREATE TABLE THIRD_PARTY_WORKFLOW_ASSIGNMENT (
    ASSIGNMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REQUEST_ID NUMBER NOT NULL,
    ASSIGNMENT_ROLE VARCHAR2(40) NOT NULL,
    ASSIGNED_EMPID NUMBER NOT NULL,
    ASSIGNED_BY_EMPID NUMBER NOT NULL,
    ASSIGNED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT FK_TP_ASSIGN_REQUEST
        FOREIGN KEY (REQUEST_ID) REFERENCES THIRD_PARTY_REQUEST (REQUEST_ID),
    CONSTRAINT FK_TP_ASSIGN_EMPLOYEE
        FOREIGN KEY (ASSIGNED_EMPID) REFERENCES EMPLOYEE (EMPID),
    CONSTRAINT FK_TP_ASSIGN_BY_EMPLOYEE
        FOREIGN KEY (ASSIGNED_BY_EMPID) REFERENCES EMPLOYEE (EMPID),
    CONSTRAINT UQ_TP_ASSIGN_ROLE
        UNIQUE (REQUEST_ID, ASSIGNMENT_ROLE),
    CONSTRAINT CHK_TP_ASSIGN_ROLE CHECK (
        ASSIGNMENT_ROLE IN (
            'GRANT_OPERATOR',
            'REVOKE_OPERATOR',
            'REVOKE_REVIEWER'
        )
    )
);

COMMENT ON TABLE THIRD_PARTY_WORKFLOW_ASSIGNMENT IS
    'Current internal employee assignments for each third-party request';
COMMENT ON COLUMN THIRD_PARTY_WORKFLOW_ASSIGNMENT.ASSIGNMENT_ROLE IS
    'GRANT_OPERATOR, REVOKE_OPERATOR, or REVOKE_REVIEWER';
COMMENT ON COLUMN THIRD_PARTY_WORKFLOW_ASSIGNMENT.ASSIGNED_EMPID IS
    'Infrastructure employee assigned to the role';
COMMENT ON COLUMN THIRD_PARTY_WORKFLOW_ASSIGNMENT.ASSIGNED_BY_EMPID IS
    'Technical employee who made the assignment';

CREATE INDEX IX_TP_ASSIGN_EMPLOYEE
    ON THIRD_PARTY_WORKFLOW_ASSIGNMENT (
        ASSIGNED_EMPID,
        ASSIGNMENT_ROLE,
        REQUEST_ID
    );

CREATE TABLE THIRD_PARTY_WORKFLOW_ACTION (
    ACTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REQUEST_ID NUMBER NOT NULL,
    ACTION_TYPE VARCHAR2(50) NOT NULL,
    FROM_STATUS VARCHAR2(40),
    TO_STATUS VARCHAR2(40) NOT NULL,
    ACTOR_TYPE VARCHAR2(30) NOT NULL,
    ACTOR_EMPID NUMBER,
    COMMENT_TEXT CLOB,
    ACTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT FK_TP_ACTION_REQUEST
        FOREIGN KEY (REQUEST_ID) REFERENCES THIRD_PARTY_REQUEST (REQUEST_ID),
    CONSTRAINT FK_TP_ACTION_EMPLOYEE
        FOREIGN KEY (ACTOR_EMPID) REFERENCES EMPLOYEE (EMPID),
    CONSTRAINT CHK_TP_ACTION_ACTOR CHECK (
        (ACTOR_TYPE = 'INTERNAL' AND ACTOR_EMPID IS NOT NULL)
        OR (ACTOR_TYPE IN ('EXTERNAL', 'SYSTEM'))
    ),
    CONSTRAINT CHK_TP_ACTION_TYPE CHECK (
        ACTION_TYPE IN (
            'WORKFLOW_MIGRATED',
            'EXTERNAL_SUBMITTED',
            'SECTION_HEAD_SUBMITTED',
            'IT_DIRECTOR_APPROVED',
            'IT_DIRECTOR_REJECTED',
            'OPERATOR_COMPLETED',
            'EXTERNAL_ACCEPTED',
            'EXTERNAL_REJECTED',
            'REVOKER_COMPLETED',
            'REVOKE_REVIEWER_APPROVED',
            'REVOKE_REVIEWER_REJECTED',
            'SECTION_HEAD_REPORTED',
            'FINAL_CERTIFIED'
        )
    )
);

COMMENT ON TABLE THIRD_PARTY_WORKFLOW_ACTION IS
    'Immutable business workflow history and comments for third-party requests';
COMMENT ON COLUMN THIRD_PARTY_WORKFLOW_ACTION.ACTION_TYPE IS
    'Business action that moved or recorded the workflow';
COMMENT ON COLUMN THIRD_PARTY_WORKFLOW_ACTION.ACTOR_TYPE IS
    'INTERNAL, EXTERNAL, or SYSTEM';
COMMENT ON COLUMN THIRD_PARTY_WORKFLOW_ACTION.COMMENT_TEXT IS
    'Actor comment, work result, rejection reason, or final report';

CREATE INDEX IX_TP_ACTION_REQUEST
    ON THIRD_PARTY_WORKFLOW_ACTION (REQUEST_ID, ACTED_AT);

CREATE INDEX IX_TP_ACTION_ACTOR
    ON THIRD_PARTY_WORKFLOW_ACTION (ACTOR_EMPID, ACTED_AT);

BEGIN
    EXECUTE IMMEDIATE
        'ALTER TABLE THIRD_PARTY_REQUEST DROP CONSTRAINT CHK_THIRD_PARTY_REQ_STATUS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -2443 THEN
            RAISE;
        END IF;
END;
/

-- Existing submitted requests enter the first internal workflow step.
INSERT INTO THIRD_PARTY_WORKFLOW_ACTION (
    REQUEST_ID,
    ACTION_TYPE,
    FROM_STATUS,
    TO_STATUS,
    ACTOR_TYPE,
    ACTOR_EMPID,
    COMMENT_TEXT,
    ACTED_AT
)
SELECT
    REQUEST_ID,
    'WORKFLOW_MIGRATED',
    STATUS,
    'PENDING_SECTION_HEAD',
    'SYSTEM',
    NULL,
    'Existing submitted request migrated into the third-party workflow.',
    SYSTIMESTAMP
FROM THIRD_PARTY_REQUEST
WHERE STATUS IN ('SUBMITTED', 'PENDING_REVIEW');

UPDATE THIRD_PARTY_REQUEST
SET STATUS = 'PENDING_SECTION_HEAD',
    UPDATED_AT = SYSTIMESTAMP
WHERE STATUS IN ('SUBMITTED', 'PENDING_REVIEW');

ALTER TABLE THIRD_PARTY_REQUEST ADD CONSTRAINT CHK_THIRD_PARTY_REQ_STATUS CHECK (
    STATUS IN (
        'LINK_CREATED',
        'SUBMITTED',
        'PENDING_SECTION_HEAD',
        'PENDING_IT_DIRECTOR',
        'PENDING_OPERATOR',
        'PENDING_EXTERNAL_ACCEPTANCE',
        'PENDING_REVOKER',
        'PENDING_REVOKE_REVIEWER',
        'PENDING_SECTION_HEAD_REPORT',
        'PENDING_FINAL_CERTIFICATION',
        'COMPLETED',
        'REJECTED',
        'CANCELLED'
    )
);

CREATE INDEX IX_TP_REQUEST_WORKFLOW_STATUS
    ON THIRD_PARTY_REQUEST (STATUS, UPDATED_AT);

-- Keep the Codex/read-only role able to inspect newly added workflow tables.
GRANT SELECT ON THIRD_PARTY_WORKFLOW_ASSIGNMENT TO SLF_READ_ROLE;
GRANT SELECT ON THIRD_PARTY_WORKFLOW_ACTION TO SLF_READ_ROLE;

COMMIT;
